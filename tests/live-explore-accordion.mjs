import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Window} from 'happy-dom';
const source=fs.readFileSync('app/yonetim/gezi-yerleri/route.ts','utf8');
const match=source.match(/new Response\(("(?:\\.|[^"\\])*"),\{headers:/);
assert.ok(match,'HTML response exists');
const html=JSON.parse(match[1]),window=new Window({url:'https://test.example/yonetim/gezi-yerleri',settings:{disableJavaScriptFileLoading:true,disableCSSFileLoading:true}});
const data={version:1,role:'admin',places:[{id:'assos',title:'Assos Antik Kenti',category:'Tarih & kültür',region:'Assos & Ayvacık',durationMinutes:90,mapQuery:'Assos',rank:1,description:'Test',notes:'',hours:'',fee:'',images:['/photos/resort.jpg'],active:true},{id:'kadirga',title:'Kadırga Koyu',category:'Plajlar',region:'Assos & Ayvacık',durationMinutes:120,mapQuery:'Kadırga',rank:4,description:'Test 2',notes:'',hours:'',fee:'',images:['/photos/beach.jpg'],active:true}]};
window.fetch=async input=>({ok:true,json:async()=>String(input).includes('central-places')?{places:[]}:{...data}});
window.document.write(html);
for(const script of window.document.querySelectorAll('script'))window.eval(script.textContent);
await new Promise(resolve=>setTimeout(resolve,80));
const buttons=()=>[...window.document.querySelectorAll('[data-live-edit]')];
assert.equal(buttons().length,2,'two existing live places rendered');
const click=id=>{const b=buttons().find(x=>x.dataset.liveEdit===id);assert.ok(b,'button exists');b.click()};
const editor=window.document.getElementById('live-editor');
click('assos');assert.equal(editor.hidden,false,'first open');assert.equal(editor.previousElementSibling?.dataset.liveRow,'assos');
click('assos');assert.equal(editor.hidden,true,'first close');
click('assos');assert.equal(editor.hidden,false,'reopen same place');
click('kadirga');assert.equal(editor.hidden,false,'switch to next');assert.equal(editor.previousElementSibling?.dataset.liveRow,'kadirga');
click('kadirga');assert.equal(editor.hidden,true,'close second');
click('assos');assert.equal(editor.hidden,false,'open after switching back');
window.document.getElementById('live-cancel').click();assert.equal(editor.hidden,true,'cancel closes');
click('kadirga');assert.equal(editor.hidden,false,'open after cancel');
console.log('PASS: live explore accordion open/close/reopen/switch/cancel');
